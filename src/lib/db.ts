export function readDatabase(): DatabaseSchema {
  try {
    if (!fs.existsSync(DB_PATH)) {
      const defaultData = getDefaultDatabase();
      writeDatabase(defaultData);
      return defaultData;
    }
    const raw = fs.readFileSync(DB_PATH, 'utf-8');
    return JSON.parse(raw) as DatabaseSchema;
  } catch (error) {
    console.error('Error reading database, falling back to default:', error);
    return getDefaultDatabase();
  }
}

export function writeDatabase(data: DatabaseSchema): void {
  try {
    const dir = path.dirname(DB_PATH);
    if (!fs.existsSync(dir)) {
      fs.mkdirSync(dir, { recursive: true });
    }
    fs.writeFileSync(DB_PATH, JSON.stringify(data, null, 2), 'utf-8');
  } catch (error) {
    console.error('Error writing database:', error);
  }
}

export function logAudit(
  church_id: string,
  user_name: string,
  action: 'CREATE' | 'UPDATE' | 'DELETE' | 'REVERSE' | 'APPROVE' | 'LOGIN' | 'EXPORT',
  module: string,
  record_id?: string,
  details?: Record<string, any>
) {
  const db = readDatabase();
  const log: AuditLog = {
    id: 'aud-' + Date.now(),
    church_id,
    user_name,
    action,
    module,
    record_id,
    details,
    ip_address: '127.0.0.1',
    created_at: new Date().toISOString(),
  };
  db.audit_logs.unshift(log);
  if (db.audit_logs.length > 200) {
    db.audit_logs = db.audit_logs.slice(0, 200);
  }
  writeDatabase(db);
}
